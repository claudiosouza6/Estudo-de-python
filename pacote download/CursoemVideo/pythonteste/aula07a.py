n1 = int(input('Digite o primeiro valor: '))
n2 = int(input('Digite o segundo valor: '))
soma = n1 + n2
subtracao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2
divisaoInteira = n1 // n2
exponenciacao = n1 ** n2
print('A soma é {}, \na subtracao é {}, \na multiplicacao é {}, \na divisao é {:.3f}, \na divisão inteira é {}  \na exponenciação é {}'.format(soma, subtracao, multiplicacao, divisao, divisaoInteira, exponenciacao))